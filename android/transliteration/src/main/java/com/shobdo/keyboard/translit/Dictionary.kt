package com.shobdo.keyboard.translit

/**
 * A single Bengali dictionary entry keyed by a Latin (Banglish) form.
 *
 * @property latin the Banglish form (lowercase, no diacritics). Used as a
 *   lookup key. Duplicate Latin keys are allowed — a Latin form may map to
 *   multiple Bengali readings (e.g. "valo" → ভালো / ভাল).
 * @property bengali the Bengali text to insert.
 * @property frequency higher is more likely. Used only for tie-breaking
 *   between dictionary matches; absolute magnitude is not exposed.
 */
public data class DictionaryEntry(
    val latin: String,
    val bengali: String,
    val frequency: Int = 1,
)

/**
 * Read-only Bengali dictionary interface. The M2 implementation ships a
 * small hand-curated seed list. Later milestones will merge a personal
 * (learned) dictionary and possibly a downloadable frequency list.
 */
public interface BengaliDictionary {
    public fun lookup(latin: String): List<DictionaryEntry>
}

